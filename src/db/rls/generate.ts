// STORY-011 — security-and-tenancy.md §3 "Forced row-level security". This
// module is a PURE function: no database access, no table-name literals of
// its own. Every table-specific decision comes from src/db/conventions.ts as
// declared data (GLOBAL_TABLES, TENANT_SCOPE_COLUMN, PORTAL_READABLE_TABLES,
// PORTAL_SELF_SCOPED_TABLES, RLS_POLICY_ROLES) — the one exception,
// `project_id`, is a structural column-name convention shared by every
// project-descendant table, not a specific table's name.
//
// The migration this generates (0006_generated_rls_policies.up.sql) is
// committed like every other migration, NOT regenerated dynamically at
// apply-time — `pnpm db:rls-generate` writes it once, `--check` verifies the
// on-disk file still matches what the generator would produce today.

export interface TableDescriptor {
  readonly name: string;
  readonly columns: ReadonlySet<string>;
}

export const GENERATED_MIGRATION_NAME = "0006_generated_rls_policies";

const HEADER = `-- STORY-011 — security-and-tenancy.md §3 "Forced row-level security".
-- GENERATED BY src/db/rls/generate.ts — DO NOT HAND-EDIT.
-- Regenerate with \`pnpm db:rls-generate\`.`;

// Verbatim from security-and-tenancy.md §3. The \`, true\` (missing_ok) on
// current_setting is what makes an unset GUC return NULL instead of raising —
// that NULL is the entire fail-closed guarantee: workspace_id = NULL
// evaluates to NULL (not true), so an un-contextualised query returns zero
// rows and every write is rejected. current_scope_projects() deliberately
// returns an empty array (not NULL) when unset — fail-closed via
// \`= ANY(empty array)\` being false, the same property by a different route.
const ACCESSOR_FUNCTIONS_SQL = `CREATE OR REPLACE FUNCTION app.current_workspace() RETURNS uuid
LANGUAGE sql STABLE PARALLEL SAFE AS $$
  SELECT NULLIF(current_setting('app.current_workspace_id', true), '')::uuid
$$;

CREATE OR REPLACE FUNCTION app.current_actor() RETURNS uuid
LANGUAGE sql STABLE PARALLEL SAFE AS $$
  SELECT NULLIF(current_setting('app.current_actor_id', true), '')::uuid
$$;

CREATE OR REPLACE FUNCTION app.current_scope_projects() RETURNS uuid[]
LANGUAGE sql STABLE PARALLEL SAFE AS $$
  SELECT COALESCE(
    string_to_array(NULLIF(current_setting('app.current_scope_projects', true), ''), ',')::uuid[],
    ARRAY[]::uuid[])
$$;`;

// STORY-011 — the partition RLS hole, verified by direct probe:
// ENABLE/FORCE ROW LEVEL SECURITY applied to a partitioned PARENT table does
// NOT cascade to its partition children. Querying a partition child directly
// (naming it instead of its parent) bypasses every policy above entirely —
// pg_class shows the parent with relrowsecurity/relforcerowsecurity both
// true and the child with BOTH still false. app.apply_tenant_rls(target)
// fixes this for one partition at a time: it discovers `target`'s parent via
// pg_inherits, copies the parent's ws_isolation_* policy predicate onto the
// child verbatim (so it never hardcodes workspace_id vs. a different scope
// column), and is idempotent. STORY-013's monthly partition-maintenance job
// makes exactly one call to this per new partition it creates (see that
// story's Technical Notes) — otherwise every new partition reopens this hole.
//
// Fix pass item 8 — the CREATE POLICY's role list is interpolated from
// RLS_POLICY_ROLES.forAll HERE, at GENERATION time (this whole SQL body is
// generator output, same as every ws_isolation_* policy above), rather than
// hardcoded as a second, independent string literal inside the function
// body. conventions.ts's own comment on RLS_POLICY_ROLES says this constant
// exists "so a future 5th runtime role forces a conscious decision" — a
// second hardcoded copy here would silently apply a new role to all 59
// parent tables and NOT to any partition child, a hard-to-diagnose
// "works on the parent, empty on the child" bug.
//
// Fix pass item 9 — apply_tenant_rls deliberately copies ONLY the
// ws_isolation_* policy to a partition child, never the table's
// portal_scope_* policy (where one exists — of the three partitioned tables,
// answer_captures, mention_facts, and citation_facts are all portal-readable).
// This is not a gap: `nominara_portal` NEVER queries a partition child by
// name — the portal application layer only ever reads through the PARENT
// table (`answer_captures`, not `answer_captures_2026_08`), and Postgres
// routes that query to the correct child via its own partition pruning
// AFTER the parent's portal_scope_* policy has already filtered by workspace
// and project. Verified fail-closed independent of this asymmetry: a
// portal session querying a partition CHILD by name gets zero rows (no
// portal_scope_* policy exists on the child at all, and FORCE ROW LEVEL
// SECURITY with no matching policy denies by default), and a portal session
// querying the PARENT gets exactly its in-scope rows (proven by
// integration test). Copying portal_scope_* onto every child would be
// redundant work for no additional protection, since the parent's own
// policy already fully governs what a portal role can see regardless of
// how many partitions exist underneath it.
const APPLY_TENANT_RLS_SQL = `CREATE OR REPLACE FUNCTION app.apply_tenant_rls(target regclass)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  parent_oid   oid;
  parent_name  text;
  target_name  text;
  policy_name  text;
  policy_qual  text;
  policy_check text;
BEGIN
  SELECT inhparent INTO parent_oid FROM pg_inherits WHERE inhrelid = target;
  IF parent_oid IS NULL THEN
    RAISE EXCEPTION 'app.apply_tenant_rls: % is not a partition of any table', target;
  END IF;

  SELECT relname INTO parent_name FROM pg_class WHERE oid = parent_oid;
  SELECT relname INTO target_name FROM pg_class WHERE oid = target;

  SELECT qual, with_check INTO policy_qual, policy_check
    FROM pg_policies
   WHERE schemaname = 'public'
     AND tablename = parent_name
     AND policyname = 'ws_isolation_' || parent_name;

  IF policy_qual IS NULL THEN
    RAISE EXCEPTION 'app.apply_tenant_rls: parent table % has no ws_isolation policy to copy', parent_name;
  END IF;

  policy_name := 'ws_isolation_' || target_name;

  EXECUTE format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY', target);
  EXECUTE format('ALTER TABLE %s FORCE  ROW LEVEL SECURITY', target);

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
     WHERE schemaname = 'public' AND tablename = target_name AND policyname = policy_name
  ) THEN
    EXECUTE format(
      'CREATE POLICY %I ON %s FOR ALL TO ${RLS_POLICY_ROLES.forAll.join(", ")} USING (%s) WITH CHECK (%s)',
      policy_name, target, policy_qual, policy_check
    );
  END IF;
END;
$$;

-- Apply it to every partition child that exists today, discovered via
-- pg_inherits rather than named — partition names are computed dynamically
-- at migration-apply time (0003_projects_prompts_captures.up.sql), so this
-- migration cannot hardcode them. Idempotent: re-running this DO block on an
-- already-fixed partition is a no-op (ENABLE/FORCE tolerate repetition, and
-- the function itself checks pg_policies before creating).
DO $$
DECLARE
  child regclass;
BEGIN
  FOR child IN
    -- pg_inherits also records PARTITIONED INDEX inheritance (e.g. each
    -- partition's copy of answer_captures_pkey is an inhrelid of the
    -- parent index), not only table partitioning — c.relkind = 'r' excludes
    -- those; a partition child table is always an ordinary relation, never
    -- itself partitioned further in this schema.
    SELECT c.oid::regclass
      FROM pg_inherits i
      JOIN pg_class c ON c.oid = i.inhrelid
      JOIN pg_class p ON p.oid = i.inhparent
      JOIN pg_namespace n ON n.oid = p.relnamespace
     WHERE n.nspname = 'public'
       AND c.relkind = 'r'
       AND p.relkind = 'p'
  LOOP
    PERFORM app.apply_tenant_rls(child);
  END LOOP;
END $$;`;

/**
 * Classification order (AC 24 / Test Scenario 6): GLOBAL_TABLES is checked by
 * the caller before this is invoked. This resolves the scope column for
 * every other table, throwing when none of the three remedies apply.
 */
function resolveScopeColumn(table: TableDescriptor): string {
  const explicit = TENANT_SCOPE_COLUMN[table.name];
  if (explicit) {
    return explicit;
  }
  if (table.columns.has("workspace_id")) {
    return "workspace_id";
  }
  throw new Error(
    `src/db/rls/generate.ts: table "${table.name}" has neither a "workspace_id" column nor an ` +
      `explicit TENANT_SCOPE_COLUMN entry, and is not listed in GLOBAL_TABLES. A new table cannot ` +
      `ship without isolation — fix one of: (1) add a "workspace_id" column, (2) add an explicit ` +
      `entry to TENANT_SCOPE_COLUMN (like workspaces' own "id" exception), or (3) if this is a ` +
      `catalog, build-time artifact, or global-identity table, add it to GLOBAL_TABLES. ` +
      `All three live in src/db/conventions.ts.`,
  );
}

/**
 * The portal policy's project-scope conjunct, or null if this table has
 * none. Exported for direct unit testing of the (currently unreached by any
 * real table) fallback branch — see STORY-011-E-2.
 */
export function resolveProjectPredicate(table: TableDescriptor): string | null {
  if ((PORTAL_SELF_SCOPED_TABLES as readonly string[]).includes(table.name)) {
    return "id = ANY (app.current_scope_projects())";
  }
  if (table.columns.has("project_id")) {
    return "project_id = ANY (app.current_scope_projects())";
  }
  // STORY-011-E-2 (see that story's Implementation Decisions section) — a
  // portal-readable table with no project_id column and not in
  // PORTAL_SELF_SCOPED_TABLES falls back to workspace-scope only, because an
  // EXISTS-subquery join to narrow scope further is exactly what AC 26 rules
  // out ("scope enforced without a join"). Originally exercised by
  // source_domains/brand_themes; both were REMOVED from PORTAL_READABLE_TABLES
  // in this fix pass instead of shipping with that gap (security-and-tenancy
  // .md's ISO-09 requires scope hold "even within the same workspace" — a
  // workspace-only fallback can't satisfy that for a genuinely
  // project-scoped share token), so this branch is currently unreached by any
  // real table. Left in place, not deleted: a future story could
  // legitimately re-add a workspace-only table to PORTAL_READABLE_TABLES with
  // this exact, deliberate, disclosed fallback as its considered decision —
  // this is the code that decision would need, not a bug to clean up.
  return null;
}

/** A structured (not SQL-text) description of one policy the generator expects to exist — the shared source of truth src/db/rls/rls-check.ts compares against `pg_policies`, so that comparison never has to re-parse generated SQL text. */
export interface ExpectedPolicy {
  readonly table: string;
  readonly policyName: string;
  readonly cmd: "ALL" | "SELECT";
  readonly roles: readonly string[];
  readonly using: string;
  readonly withCheck: string | null;
}

/**
 * The structured equivalent of what generateRlsSql renders as SQL text —
 * one ALL-policy entry per classifiable tenant table, plus a SELECT-policy
 * entry for each portal-readable one. GLOBAL_TABLES entries are skipped
 * (caller's responsibility, mirroring generateRlsSql itself); an
 * unclassifiable table throws, via the same resolveScopeColumn used for
 * SQL generation, so the two paths can never independently drift.
 */
export function computeExpectedPolicies(tables: readonly TableDescriptor[]): ExpectedPolicy[] {
  const globalSet = new Set<string>(GLOBAL_TABLES);
  const portalSet = new Set<string>(PORTAL_READABLE_TABLES);
  const sorted = [...tables].sort((a, b) => a.name.localeCompare(b.name));

  const expected: ExpectedPolicy[] = [];
  for (const table of sorted) {
    if (globalSet.has(table.name)) {
      continue;
    }
    const scopeColumn = resolveScopeColumn(table);
    const wsUsing = `${scopeColumn} = app.current_workspace()`;
    expected.push({
      table: table.name,
      policyName: `ws_isolation_${table.name}`,
      cmd: "ALL",
      roles: RLS_POLICY_ROLES.forAll,
      using: wsUsing,
      withCheck: wsUsing,
    });

    if (portalSet.has(table.name)) {
      const projectPredicate = resolveProjectPredicate(table);
      const portalUsing = projectPredicate ? `${wsUsing} AND ${projectPredicate}` : wsUsing;
      expected.push({
        table: table.name,
        policyName: `portal_scope_${table.name}`,
        cmd: "SELECT",
        roles: [RLS_POLICY_ROLES.portal],
        using: portalUsing,
        withCheck: null,
      });
    }
  }
  return expected;
}

// CREATE POLICY has no native IF NOT EXISTS form (unlike CREATE ROLE / most
// other DDL this repo already guards — see 0005's DO-block pattern for
// roles). Every policy this generator emits is therefore wrapped in the same
// "check pg_policies, then create" DO block, so 0006 is idempotent when
// re-applied directly — required by this story's own migration-hygiene test,
// and the same idempotency property every prior migration in this repo has.
// Renders from an ExpectedPolicy directly (the SAME structured value
// src/db/rls/rls-check.ts compares against pg_policies), so the SQL text and
// the drift-check comparison can never independently disagree about what a
// policy's USING/WITH CHECK clause should be.
function guardedCreatePolicy(policy: ExpectedPolicy): string {
  const usingRendered = policy.using.includes(" AND ") ? policy.using.replace(" AND ", "\n         AND ") : policy.using;

  const createLines =
    policy.cmd === "ALL"
      ? [
          `CREATE POLICY ${policy.policyName} ON ${policy.table}`,
          `  FOR ALL TO ${policy.roles.join(", ")}`,
          `  USING      (${usingRendered})`,
          `  WITH CHECK (${policy.withCheck});`,
        ]
      : [
          `CREATE POLICY ${policy.policyName} ON ${policy.table}`,
          `  FOR SELECT TO ${policy.roles.join(", ")}`,
          `  USING (${usingRendered});`,
        ];

  const indented = createLines.map((line) => `    ${line}`).join("\n");
  return [
    "DO $$ BEGIN",
    "  IF NOT EXISTS (",
    `    SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = '${policy.table}' AND policyname = '${policy.policyName}'`,
    "  ) THEN",
    indented,
    "  END IF;",
    "END $$;",
  ].join("\n");
}

function renderTableBlock(tableName: string, policies: readonly ExpectedPolicy[]): string {
  const lines = [`ALTER TABLE ${tableName} ENABLE ROW LEVEL SECURITY;`, `ALTER TABLE ${tableName} FORCE  ROW LEVEL SECURITY;`];
  for (const policy of policies) {
    lines.push("", guardedCreatePolicy(policy));
  }
  return lines.join("\n");
}

/**
 * Fix pass item 11 — the sorted list of all classifiable tenant table
 * (BASE table, never a partition child) names, derived from the exact same
 * `computeExpectedPolicies` classification that produces migration 0006's
 * `ws_isolation_*` policies, so this list and that migration's table set can
 * never silently diverge. This is what `src/db/rls/tenant-tables.generated
 * .ts` (committed, generated by the CLI below) exports as `TENANT_TABLES`
 * for `src/tenancy/query-guard.ts` to consume — NFR-SEC-01 names "a table in
 * the generated `TENANT_TABLES` set", and before this fix nothing actually
 * generated one.
 */
export function computeTenantTableNames(tables: readonly TableDescriptor[]): string[] {
  const names = new Set<string>();
  for (const policy of computeExpectedPolicies(tables)) {
    if (policy.policyName === `ws_isolation_${policy.table}`) {
      names.add(policy.table);
    }
  }
  return [...names].sort();
}

/**
 * Generates the full RLS migration body for `tables`. Output order:
 * header, the 3 accessor functions, one block per tenant table (ALPHABETICAL
 * by name — deterministic, minimal diffs on regeneration, and the order
 * computeExpectedPolicies already produces), then the app.apply_tenant_rls
 * function and its partition-discovery DO block.
 *
 * GLOBAL_TABLES entries emit nothing — they are secured by GRANT alone
 * (STORY-010), never RLS. Every other table must resolve a scope column or
 * this throws (see resolveScopeColumn, via computeExpectedPolicies).
 */
export function generateRlsSql(tables: readonly TableDescriptor[]): string {
  const expectedPolicies = computeExpectedPolicies(tables);

  const policiesByTable = new Map<string, ExpectedPolicy[]>();
  for (const policy of expectedPolicies) {
    const forTable = policiesByTable.get(policy.table) ?? [];
    forTable.push(policy);
    policiesByTable.set(policy.table, forTable);
  }

  const blocks = [...policiesByTable.entries()].map(([tableName, policies]) => renderTableBlock(tableName, policies));

  return [HEADER, ACCESSOR_FUNCTIONS_SQL, ...blocks, APPLY_TENANT_RLS_SQL].join("\n\n") + "\n";
}

