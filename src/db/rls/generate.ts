/** Path of the committed, generated TENANT_TABLES module (fix pass item 11). */
export const TENANT_TABLES_FILE = path.join(path.dirname(fileURLToPath(import.meta.url)), "tenant-tables.generated.ts");

/**
 * Renders the committed `tenant-tables.generated.ts` module body. Mirrors
 * 0006.up.sql's own "GENERATED, DO NOT HAND-EDIT" header convention.
 * Deliberately documents, rather than attempts to derive, the one thing this
 * list structurally cannot cover: partition CHILD table names, which are
 * computed dynamically at migration-apply time (or by a future STORY-013
 * maintenance job), never known ahead of time the way a base table's name is.
 */
export function renderTenantTablesModule(tableNames: readonly string[]): string {
  const entries = tableNames.map((name) => `  "${name}",`).join("\n");
  return `// STORY-011 fix pass item 11 — security-and-tenancy.md §4's NFR-SEC-01
// ("a table in the generated \`TENANT_TABLES\` set").
// GENERATED BY src/db/rls/generate.ts — DO NOT HAND-EDIT.
// Regenerate with \`pnpm db:rls-generate\`.
//
// Every classifiable tenant BASE table name (never a partition child),
// derived from the exact same computeExpectedPolicies classification that
// produces migration 0006 — this set and that migration's table set can
// never silently diverge.
//
// KNOWN GAP, disclosed rather than silently accepted (README.md gap G-8):
// partition CHILD table names (e.g. \`answer_captures_2026_08\`) are computed
// dynamically at migration-apply time / by a future STORY-013 maintenance
// job — they cannot be enumerated statically here the way a base table's
// name can. A query naming a partition child directly, instead of its
// parent, is therefore invisible to src/tenancy/query-guard.ts's heuristic.
// This does not weaken the actual security boundary: RLS (migration 0006 +
// app.apply_tenant_rls) is NOT fooled by this and denies such a query
// regardless — see query-guard.ts's own module header.

export const TENANT_TABLES: ReadonlySet<string> = new Set([
${entries}
]);
`;
}

async function withShadowDatabase<T>(fn: (shadow: Awaited<ReturnType<typeof connect>>) => Promise<T>): Promise<T> {
  const maintenanceUrl = requireDatabaseUrl();
  const shadowDbName = `nominara_rlsgen_${Date.now()}`;
  const maintenance = await connect(maintenanceUrl);
  try {
    await maintenance.query(`CREATE DATABASE ${shadowDbName}`);
  } finally {
    await maintenance.end();
  }

  const shadowUrl = new URL(maintenanceUrl);
  shadowUrl.pathname = `/${shadowDbName}`;
  const shadow = await connect(shadowUrl.toString());

  try {
    await migrateUp(shadow);
    return await fn(shadow);
  } finally {
    await shadow.end();
    const cleanup = await connect(maintenanceUrl);
    try {
      await cleanup.query(`DROP DATABASE IF EXISTS ${shadowDbName}`);
    } finally {
      await cleanup.end();
    }
  }
}

async function generateAgainstShadowDatabase(): Promise<{ migrationSql: string; tenantTablesModule: string }> {
  return withShadowDatabase(async (shadow) => {
    const tables = await introspectTables(shadow);
    return {
      migrationSql: generateRlsSql(tables),
      tenantTablesModule: renderTenantTablesModule(computeTenantTableNames(tables)),
    };
  });
}

async function main() {
  const checkOnly = process.argv.includes("--check");
  const upPath = path.join(MIGRATIONS_DIR, `${GENERATED_MIGRATION_NAME}.up.sql`);

  const { migrationSql, tenantTablesModule } = await generateAgainstShadowDatabase();

  if (checkOnly) {
    const onDiskMigration = await readFile(upPath, "utf8").catch(() => null);
    const onDiskTenantTables = await readFile(TENANT_TABLES_FILE, "utf8").catch(() => null);

    if (onDiskMigration !== migrationSql) {
      console.error(`db:rls-generate --check failed: ${upPath} is out of date with the generator.`);
      console.error("Run `pnpm db:rls-generate` and commit the result.");
      process.exit(1);
    }

    if (onDiskTenantTables !== tenantTablesModule) {
      console.error(`db:rls-generate --check failed: ${TENANT_TABLES_FILE} is out of date with the generator.`);
      console.error("Run `pnpm db:rls-generate` and commit the result.");
      process.exit(1);
    }

    console.log("db:rls-generate --check passed: the committed migration and TENANT_TABLES module both match the generator.");
    return;
  }

  await writeFile(upPath, migrationSql, "utf8");
  console.log(`wrote ${upPath}`);
  await writeFile(TENANT_TABLES_FILE, tenantTablesModule, "utf8");
  console.log(`wrote ${TENANT_TABLES_FILE}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await main();
}
