-- Owner decision 83 (c) (2026-11-09) — GET /v1/portal/sources: a nominara_portal SELECT policy on source_domains, limited to domains with a
-- project_source_index row for a project in app.current_scope_projects().
--
-- ⚠ THIS OVERRIDES THE STORY-011-E-2 NOTE (conventions.ts's PORTAL_READABLE_TABLES comment, and AC 26 "scope enforced without a join"),
-- which removed source_domains from the portal-readable set because it has no project_id column and a workspace-only policy would let a
-- project-scoped token enumerate every domain in the workspace. The owner's decision is the join below: a domain is visible only through
-- an index row of an in-scope project, so a domain that only ever appeared in an out-of-scope project stays invisible (ISO-09).
--
-- Purely additive to migration 0006: no ENABLE/FORCE (0006 already did), no ws_isolation change. project_source_index is itself portal-scoped
-- by its own project_id, so the subquery runs under the portal role's RLS too.
-- GENERATED BY src/db/rls/generate.ts — DO NOT HAND-EDIT.
-- Regenerate with `pnpm db:rls-generate`.

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'source_domains' AND policyname = 'portal_scope_source_domains'
  ) THEN
    CREATE POLICY portal_scope_source_domains ON source_domains
      FOR SELECT TO nominara_portal
      USING (workspace_id = app.current_workspace()
         AND EXISTS (SELECT 1 FROM project_source_index psi WHERE psi.source_domain_id = source_domains.id AND psi.project_id = ANY (app.current_scope_projects())));
  END IF;
END $$;
