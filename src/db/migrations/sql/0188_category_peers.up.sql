-- a failed peer is not seeded. Eleven categories have no peers by design (local or firm-by-firm markets).
--
-- No confidence column: a curated peer carries a fixed 1.0 at proposal time (decision 91), a constant in code, not a per-row estimate.
-- GLOBAL and READ-ONLY to every runtime role, as business_categories.
