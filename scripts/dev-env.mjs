// STORY-004 AC3 — the .env half of `pnpm dev:up`.
//
// Dependency-free on purpose (node: built-ins only): it runs on a clean clone,
// before anything else is installed or built. Types: scripts/dev-env.d.mts.
//
// What it writes: `.env.example` with every `REPLACE_…` placeholder filled by a
// secret generated HERE, on this machine, with node:crypto — never a value
// checked into source control — plus `OTP_DEV_LOG_CODES=true` so a seeded
// owner can finish email-OTP sign-in locally. Every vendor credential stays
// unset: local development needs none (fixture adapters cover every engine).
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** Every key that names a vendor credential. A generated .env sets none of them. */
export const VENDOR_KEYS = Object.freeze([
  "GEMINI_API_KEY",
  "STRIPE_SECRET_KEY",
  "STRIPE_WEBHOOK_SECRET",
  "STRIPE_PUBLISHABLE_KEY",
  "RESEND_API_KEY",
  "RESEND_FROM_EMAIL",
  "RESEND_TO_EMAIL",
  "RESEND_WEBHOOK_SECRET",
  "GOOGLE_OAUTH_CLIENT_ID",
  "GOOGLE_OAUTH_CLIENT_SECRET",
  "GITHUB_OAUTH_CLIENT_ID",
  "GITHUB_OAUTH_CLIENT_SECRET",
  "MICROSOFT_OAUTH_CLIENT_ID",
  "MICROSOFT_OAUTH_CLIENT_SECRET",
  "STORAGE_ACCESS_KEY_ID",
  "STORAGE_SECRET_ACCESS_KEY",
]);

const ENV_LINE = /^\s*([A-Z][A-Z0-9_]*)\s*=(.*)$/u;

/** KEY=VALUE lines into a record; comments and blank lines skipped; the first `=` splits; one layer of quotes removed. */
export function parseEnvText(text) {
  const out = {};
  for (const line of text.split(/\r?\n/u)) {
    if (line.trim().startsWith("#")) continue;
    const match = ENV_LINE.exec(line);
    if (match === null) continue;
    let value = match[2].trim();
    if (value.length >= 2 && (value[0] === '"' || value[0] === "'") && value.at(-1) === value[0]) value = value.slice(1, -1);
    out[match[1]] = value;
  }
  return out;
}

function secret() {
  return randomBytes(32).toString("base64url");
}

function key32() {
  return randomBytes(32).toString("base64");
}

/** One fresh value per placeholder key. An unknown placeholder is refused, so a new REPLACE_ in .env.example cannot slip through unfilled. */
function generatedValues() {
  const { privateKey, publicKey } = generateKeyPairSync("ed25519");
  return {
    AUTH_TOKEN_ED25519_PRIVATE_KEY: privateKey.export({ type: "pkcs8", format: "der" }).toString("base64"),
    AUTH_TOKEN_ED25519_PUBLIC_KEY: publicKey.export({ type: "spki", format: "der" }).toString("base64"),
    CSRF_SECRET: secret(),
    OAUTH_STATE_SECRET: secret(),
    OTP_EMAIL_HASH_PEPPER: secret(),
    WORKSPACE_DEK_WRAPPING_KEY: key32(),
    QUEUE_JOB_SIGNING_KEY: key32(),
  };
}

/** .env.example's text with every REPLACE_ placeholder filled by a locally generated secret, and OTP_DEV_LOG_CODES=true. */
export function generateDevEnv(exampleText) {
  const values = generatedValues();
  let otpSet = false;
  const lines = exampleText.split(/\r?\n/u).map((line) => {
    if (/^#\s*OTP_DEV_LOG_CODES=true\s*$/u.test(line)) {
      otpSet = true;
      return "OTP_DEV_LOG_CODES=true";
    }
    if (line.trim().startsWith("#")) return line;
    const match = ENV_LINE.exec(line);
    if (match === null) return line;
    const [, name, raw] = match;
    if (VENDOR_KEYS.includes(name)) {
      throw new Error(`.env.example sets the vendor credential ${name}; a generated local .env must set none`);
    }
    if (!raw.trim().startsWith("REPLACE_")) return line;
    const value = values[name];
    if (value === undefined) {
      throw new Error(`.env.example has a placeholder for ${name}, which the dev bootstrap does not know how to generate (scripts/dev-env.mjs)`);
    }
    return `${name}=${value}`;
  });
  if (!otpSet) lines.push("OTP_DEV_LOG_CODES=true");
  const header = [
    "# Generated by `pnpm dev:up` (scripts/dev-env.mjs) from .env.example.",
    "# Every secret below was generated on this machine and is for LOCAL development only.",
    "# No vendor credential is set: fixture adapters cover every engine. Never commit this file.",
    "",
  ];
  return [...header, ...lines].join("\n");
}

/** The host-side URLs of the compose stack, from the same port variables docker-compose.yml interpolates. */
export function composeHostUrls(env) {
  const port = (name, fallback) => {
    const value = env[name];
    return value === undefined || value.trim() === "" ? fallback : value.trim();
  };
  const appPassword = port("NOMINARA_APP_DB_PASSWORD", "nominara_app_dev_local");
  return {
    databaseUrl: `postgres://nominara:nominara@localhost:${port("POSTGRES_PORT", "5432")}/nominara`,
    databaseUrlPooled: `postgres://nominara_app:${encodeURIComponent(appPassword)}@localhost:${port("PGBOUNCER_PORT", "6432")}/nominara`,
    valkeyCacheUrl: `redis://localhost:${port("VALKEY_PORT", "6379")}`,
    queueRedisUrl: `redis://localhost:${port("VALKEY_QUEUE_PORT", "6380")}`,
    apiUrl: `http://localhost:${port("API_PORT", "4000")}`,
    gatewayUrl: `http://localhost:${port("GATEWAY_HOST_PORT", "3001")}`,
  };
}

/** Writes `<dir>/.env` from `<dir>/.env.example` when absent; never overwrites one. Refuses a .env still holding a placeholder. */
export function ensureDevEnv(dir) {
  const path = join(dir, ".env");
  if (existsSync(path)) {
    const unfilled = Object.entries(parseEnvText(readFileSync(path, "utf8")))
      .filter(([, value]) => value.includes("REPLACE_"))
      .map(([name]) => name);
    if (unfilled.length > 0) {
      throw new Error(
        `${path} still holds REPLACE_ placeholder(s) in ${unfilled.join(", ")}. Fill them, or move the file aside and rerun to have one generated.`,
      );
    }
    return { created: false, path };
  }
  writeFileSync(path, generateDevEnv(readFileSync(join(dir, ".env.example"), "utf8")), { mode: 0o600 });
  return { created: true, path };
}
